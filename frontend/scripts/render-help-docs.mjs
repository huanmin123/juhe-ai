// 帮助文档渲染器：docs/**/*.md（唯一人工维护层）→ rendered/**/*.html（生成物，入库）。
// 与 maintenance 种子生成器同模式：源与生成物同库，`--check` 门禁钉一致（回归测试调用）。
// 用法：node scripts/render-help-docs.mjs [--check]
import { readdirSync, readFileSync, writeFileSync, existsSync, mkdirSync } from 'node:fs';
import { join, dirname, relative, sep } from 'node:path';
import { fileURLToPath } from 'node:url';
import { marked } from 'marked';

const root = dirname(dirname(fileURLToPath(import.meta.url)));
const docsRoot = join(root, 'public', 'help', 'docs');
const outRoot = join(root, 'public', 'help', 'rendered');
const manifestPath = join(root, 'public', 'help', 'manifest.json');
const checkMode = process.argv.includes('--check');

function escapeHtml(text) {
  return text.replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;');
}

// 自家 md 是受信内容，但约定禁止内联 HTML：原生 HTML token 一律转义为可见文本，
// 渲染产物因此不包含任何调用方可控标签（回归断言 rendered 无 <script>）。
marked.use({
  gfm: true,
  renderer: {
    html(token) {
      return `<!-- stripped-inline-html ${escapeHtml((token.raw || '').trim().slice(0, 60))} -->`;
    }
  }
});

function listMarkdownFiles(dir) {
  const out = [];
  for (const entry of readdirSync(dir, { withFileTypes: true })) {
    const full = join(dir, entry.name);
    if (entry.isDirectory()) out.push(...listMarkdownFiles(full));
    else if (entry.name.endsWith('.md')) out.push(full);
  }
  return out.sort();
}

function extractTitle(html) {
  const match = /<h1[^>]*>([\s\S]*?)<\/h1>/.exec(html);
  return match ? match[1].replace(/<[^>]+>/g, '').trim() : '';
}

const manifest = JSON.parse(readFileSync(manifestPath, 'utf8'));
const manifestFiles = [];
for (const audience of Object.values(manifest.audiences)) {
  for (const doc of audience.docs) manifestFiles.push(doc.file);
}

const diskFiles = listMarkdownFiles(docsRoot).map((p) => relative(docsRoot, p).split(sep).join('/'));
const problems = [];
for (const file of manifestFiles) {
  if (!diskFiles.includes(file)) problems.push(`manifest 引用了不存在的文档: ${file}`);
}
for (const file of diskFiles) {
  if (!manifestFiles.includes(file)) problems.push(`文档未登记进 manifest: ${file}`);
}
for (const file of manifestFiles) {
  if (manifestFiles.indexOf(file) !== manifestFiles.lastIndexOf(file)) {
    problems.push(`manifest 重复登记: ${file}`);
  }
}
if (problems.length) {
  console.error('manifest 与 docs/ 不一致:');
  for (const problem of problems) console.error(`  - ${problem}`);
  process.exit(1);
}

let changed = [];
let written = 0;
for (const file of diskFiles) {
  const source = readFileSync(join(docsRoot, file), 'utf8');
  const body = marked.parse(source);
  const title = extractTitle(body);
  const html = [
    `<!-- Code generated by scripts/render-help-docs.mjs from docs/${file}; DO NOT EDIT. -->`,
    `<!-- doc-title: ${title} -->`,
    body
  ].join('\n');

  const outPath = join(outRoot, file.replace(/\.md$/, '.html'));
  const previous = existsSync(outPath) ? readFileSync(outPath, 'utf8') : null;
  if (previous !== html) changed.push(file);
  if (!checkMode) {
    mkdirSync(dirname(outPath), { recursive: true });
    writeFileSync(outPath, html);
    written += 1;
  } else if (previous === null) {
    console.error(`缺少生成物（先跑 node scripts/render-help-docs.mjs 再提交）: ${file}`);
    process.exitCode = 1;
  } else if (previous !== html) {
    console.error(`生成物与 md 源不一致（跑 node scripts/render-help-docs.mjs 更新后再提交）: ${file}`);
    process.exitCode = 1;
  }
}

if (checkMode) {
  if (process.exitCode === 1) {
    console.error('help 文档渲染物与 md 源不一致。');
  } else {
    console.log(`help 文档渲染物校验通过（${diskFiles.length} 篇）。`);
  }
} else {
  console.log(`已渲染 ${written} 篇（${changed.length} 篇有变化）: public/help/rendered/`);
}
