// playableMP4 缓存 hex 常量的一次性解码结果。
var playableMP4 = sync.OnceValue(func() []byte {
	data, err := hex.DecodeString(playableMP4Hex)
	if err != nil {
		panic("mockupstream: playableMP4Hex 不是合法十六进制: " + err.Error())
	}
	return data
})

// PlayableMP4Payload 返回真实可播放的最小黑屏 MP4（ftyp/moov/mdat 完整盒
// 结构，浏览器可直接 <video> 播放）。供 chat 域问答媒体链与后续演示使用；
// /v1 域 E2E 的 magic bytes 断言仍用 mp4Payload() 占位载荷，不受影响。
func PlayableMP4Payload() []byte {
	return append([]byte(nil), playableMP4()...)
}
