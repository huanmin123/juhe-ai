function run(args: string[]): void {
  const options = parseOptions(args)
  if (options.outputPath === undefined) {
    process.stdout.write(providerModelCatalogSnapshotSQL)
  } else if (options.check) {
    const current = readFileSync(options.outputPath, 'utf8')
    if (normalizeLineEndings(current) !== normalizeLineEndings(providerModelCatalogSnapshotSQL)) {
      console.error(`provider model catalog snapshot drifted: ${options.outputPath}`)
      process.exitCode = 1
    } else {
      console.log(`provider model catalog snapshot is current: ${options.outputPath}`)
    }
  } else {
    if (existsSync(options.outputPath) && !options.force) {
      throw new Error(`refusing to overwrite existing migration without --force: ${options.outputPath}`)
    }
    mkdirSync(dirname(options.outputPath), { recursive: true })
    writeFileSync(options.outputPath, providerModelCatalogSnapshotSQL, 'utf8')
    console.log(`wrote ${rows.length} provider model rows to ${options.outputPath}`)
  }
}

function normalizeLineEndings(value: string): string {
  return value.replace(/\r\n/g, '\n')
}

function isDirectExecution(): boolean {
  const entryPath = process.argv[1]
  return Boolean(entryPath) && import.meta.url === pathToFileURL(resolve(entryPath)).href
}

interface GenerateOptions {
  check: boolean
  force: boolean
  outputPath?: string
}

function parseOptions(args: string[]): GenerateOptions {
  const options: GenerateOptions = {
    check: false,
    force: false
  }
  for (let index = 0; index < args.length; index += 1) {
    const argument = args[index]
    if (argument === '--check') {
      options.check = true
      continue
    }
    if (argument === '--force') {
      options.force = true
      continue
    }
    if (argument === '--output') {
      const outputPath = args[index + 1]
      if (!outputPath || outputPath.startsWith('--')) {
        throw new Error('--output requires a file path')
      }
      options.outputPath = resolve(outputPath)
      index += 1
      continue
    }
    throw new Error(`unknown argument: ${argument}`)
  }
  if (options.check && options.outputPath === undefined) {
    throw new Error('--check requires --output <migration-path>')
  }
  if (options.check && options.force) {
    throw new Error('--check cannot be combined with --force')
  }
  return options
}

function catalogRowSQL(row: ProviderModelPricing): string {
  const values = [
    sqlText(catalogRowID(row)),
    sqlText(row.providerCode),
    sqlText(row.model),
    sqlText('active'),
    sqlNullableText(row.mode),
    sqlNullableNumber(row.catalogOrder),
    sqlNullableText(row.releaseDate),
    sqlNullableText(row.shutdownDate),
    sqlJSON(row.supportedApiProtocols),
    sqlJSON(row.supportedServiceTiers),
    sqlJSON(row.supportedReasoningEfforts),
    sqlNullableText(row.defaultReasoningEffort),
    sqlJSON(row.codexSupportedReasoningLevels),
    sqlNullableText(row.codexDefaultReasoningLevel),
    sqlNullableText(row.codexMultiAgentVersion),
    sqlNullableNumber(row.contextWindowTokens),
    sqlNullableNumber(row.inputUsdPer1M),
    sqlNullableNumber(row.outputUsdPer1M),
    sqlNullableNumber(row.cachedInputUsdPer1M),
    sqlNullableNumber(row.cacheWriteUsdPer1M),
    sqlNullableNumber(row.cacheWrite1hUsdPer1M),
    sqlNullableNumber(row.cacheStorageUsdPer1MPerHour),
    sqlJSON(row.serviceTierPrices ?? {}),
    sqlNullableNumber(row.longContextInputTokenThreshold),
    sqlBoolean(row.longContextInputTokenThresholdInclusive === true),
    sqlNullableNumber(row.longContextInputCostMultiplier),
    sqlNullableNumber(row.longContextOutputCostMultiplier),
    sqlNullableNumber(row.imageInputUsdPer1M),
    sqlNullableNumber(row.imageOutputUsdPer1M),
    sqlNullableNumber(row.audioInputUsdPer1M),
    sqlNullableNumber(row.audioOutputUsdPer1M),
    sqlNullableNumber(row.outputUsdPerImage),
    sqlNullableNumber(row.maxInputTokens),
    sqlNullableNumber(row.maxOutputTokens),
    sqlNullableNumber(row.maxTokens),
    sqlBoolean(row.supportsPromptCaching),
    sqlBoolean(row.catalogVisible !== false),
    sqlText(row.source),
    'now()',
    'now()'
  ]

  return [
    '  (',
    `    ${values.slice(0, 8).join(', ')},`,
    `    ${values.slice(8, 15).join(', ')},`,
    `    ${values.slice(15, 22).join(', ')},`,
    `    ${values.slice(22, 28).join(', ')},`,
    `    ${values.slice(28, 33).join(', ')},`,
    `    ${values.slice(33, 36).join(', ')},`,
    `    ${values.slice(36).join(', ')}`,
    '  )'
  ].join('\n')
}

function catalogRowID(row: ProviderModelPricing): string {
  const slug = `${row.providerCode}_${row.model}`
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, '_')
    .replace(/^_+|_+$/g, '')
    .slice(0, 72)
  const hash = createHash('sha256')
    .update(`${row.providerCode}\0${row.model}`)
    .digest('hex')
    .slice(0, 12)
  return `provider_model_${slug}_${hash}`
}

function sqlText(value: string): string {
  return `'${value.replaceAll("'", "''")}'`
}

function sqlNullableText(value: string | undefined): string {
  return value === undefined ? 'NULL' : sqlText(value)
}

function sqlNullableNumber(value: number | undefined): string {
  if (value === undefined) return 'NULL'
  if (!Number.isFinite(value)) {
    throw new Error(`provider model catalog contains a non-finite number: ${value}`)
  }
  return String(value)
}

function sqlBoolean(value: boolean): string {
  return value ? 'true' : 'false'
}

function sqlJSON(value: readonly string[]): string {
  return sqlText(JSON.stringify(value))
}
