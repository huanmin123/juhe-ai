package modelcheckauth

import (
	"context"
	"database/sql"
	"testing"

	_ "modernc.org/sqlite"
)

func TestVerifySystemAccountCredentialsUsesNodePBKDF2SaltText(t *testing.T) {
	db, err := sql.Open("sqlite", "file::memory:?cache=shared")
	if err != nil {
		t.Fatal(err)
	}
	defer db.Close()
	if _, err := db.Exec(`CREATE TABLE system_accounts (id TEXT PRIMARY KEY,username TEXT NOT NULL,display_name TEXT,role TEXT NOT NULL,status TEXT NOT NULL,password_hash TEXT NOT NULL,must_change_password INTEGER NOT NULL,last_login_at TEXT)`); err != nil {
		t.Fatal(err)
	}
	if _, err := db.Exec(`CREATE TABLE system_sessions (id TEXT PRIMARY KEY,system_account_id TEXT,token_hash TEXT UNIQUE,expires_at TEXT,created_at TEXT,last_seen_at TEXT)`); err != nil {
		t.Fatal(err)
	}
	// Generated by Node crypto.pbkdf2Sync(password, saltText, 120000, 32,
	// 'sha512'), where saltText is not decoded before PBKDF2.
	const passwordHash = "pbkdf2$sha512$120000$MDEyMzQ1Njc4OWFiY2RlZg$MB16ie0MUIkgM1Xio7iCM8x9uCDqJJf5rkQ297w84fg"
	if _, err := db.Exec(`INSERT INTO system_accounts(id,username,display_name,role,status,password_hash,must_change_password) VALUES ('acct','Admin','管理员','admin','active',?,1)`, passwordHash); err != nil {
		t.Fatal(err)
	}
	auth, err := New(db, SQLite, nil)
	if err != nil {
		t.Fatal(err)
	}
	verified, ok, err := auth.VerifySystemAccountCredentials(context.Background(), "admin", "correct horse battery staple")
	if err != nil || !ok {
		t.Fatalf("verified=%+v ok=%v err=%v", verified, ok, err)
	}
	if verified.SystemAccountID != "acct" || verified.Username != "Admin" || verified.Role != "admin" || !verified.MustChangePassword || verified.CredentialRevision != hashString(passwordHash) {
		t.Fatalf("verified=%+v", verified)
	}
	issued, loginVerified, ok, err := auth.Login(context.Background(), "ADMIN", "correct horse battery staple", 14)
	if err != nil || !ok || issued.Token == "" || loginVerified.CredentialRevision != verified.CredentialRevision {
		t.Fatalf("issued=%+v verified=%+v ok=%v err=%v", issued, loginVerified, ok, err)
	}
	var sessionCount int
	if err := db.QueryRow(`SELECT COUNT(*) FROM system_sessions WHERE system_account_id='acct'`).Scan(&sessionCount); err != nil || sessionCount != 1 {
		t.Fatalf("sessionCount=%d err=%v", sessionCount, err)
	}
	for _, input := range []struct{ username, password string }{{"admin", "wrong"}, {"missing", "correct horse battery staple"}, {"", "correct horse battery staple"}} {
		if _, ok, err := auth.VerifySystemAccountCredentials(context.Background(), input.username, input.password); err != nil || ok {
			t.Fatalf("input=%+v ok=%v err=%v", input, ok, err)
		}
	}
}

func TestVerifySystemAccountCredentialsFailsClosedForMalformedOrDisabledHash(t *testing.T) {
	db, err := sql.Open("sqlite", "file::memory:?cache=shared")
	if err != nil {
		t.Fatal(err)
	}
	defer db.Close()
	if _, err := db.Exec(`CREATE TABLE system_accounts (id TEXT PRIMARY KEY,username TEXT NOT NULL,display_name TEXT,role TEXT NOT NULL,status TEXT NOT NULL,password_hash TEXT NOT NULL,must_change_password INTEGER NOT NULL)`); err != nil {
		t.Fatal(err)
	}
	if _, err := db.Exec(`INSERT INTO system_accounts VALUES ('bad','bad','Bad','admin','active','pbkdf2$sha512$0$salt$bad',0),('off','off','Off','admin','disabled','pbkdf2$sha512$120000$salt$MB16ie0MUIkgM1Xio7iCM8x9uCDqJJf5rkQ297w84fg',0)`); err != nil {
		t.Fatal(err)
	}
	auth, _ := New(db, SQLite, nil)
	for _, username := range []string{"bad", "off"} {
		if _, ok, err := auth.VerifySystemAccountCredentials(context.Background(), username, "correct horse battery staple"); err != nil || ok {
			t.Fatalf("username=%s ok=%v err=%v", username, ok, err)
		}
	}
}
