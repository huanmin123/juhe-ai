// ValidateLegacyJ3bFactCoverage checks that every known source fact has one,
// and only one, explicit disposition and that the caller supplied matching
// evidence. Missing entries, unknown entries, incomplete mappings, and absent
// retention decisions all keep Ready=false. It never opens a database or
// marks a migration complete.
func ValidateLegacyJ3bFactCoverage(inventory []LegacyJ3bFact, evidence map[string]LegacyJ3bFactEvidence) LegacyJ3bFactCoverageReport {
	report := LegacyJ3bFactCoverageReport{Facts: make(map[string]string, len(LegacyJ3bFactInventory))}
	expected := make(map[string]LegacyJ3bFact, len(LegacyJ3bFactInventory))
	for _, item := range LegacyJ3bFactInventory {
		expected[item.Name] = item
	}
	provided := make(map[string]LegacyJ3bFact, len(inventory))
	for _, item := range inventory {
		name := strings.TrimSpace(item.Name)
		if name == "" {
			report.Facts["__unnamed__"] = "inventory entry has no name"
			continue
		}
		if _, duplicate := provided[name]; duplicate {
			report.Facts[name] = "duplicate inventory entry"
			continue
		}
		provided[name] = item
	}

	complete := true
	ready := true
	for name, expectedItem := range expected {
		item, found := provided[name]
		if !found {
			report.Facts[name] = "coverage decision missing"
			complete, ready = false, false
			continue
		}
		if item.SourceSchema != expectedItem.SourceSchema || item.SourceTable != expectedItem.SourceTable || item.Scope != expectedItem.Scope {
			report.Facts[name] = "source mapping drift"
			complete, ready = false, false
			continue
		}
		if item.Disposition == LegacyFactBackfill && (strings.TrimSpace(item.TargetSchema) == "" || strings.TrimSpace(item.TargetTable) == "") {
			report.Facts[name] = "target mapping missing"
			complete, ready = false, false
			continue
		}
		if item.Disposition == LegacyFactRetain && strings.TrimSpace(item.RetentionWhy) == "" {
			report.Facts[name] = "retention decision missing"
			complete, ready = false, false
			continue
		}
		factEvidence, evidenceFound := evidence[name]
		if !evidenceFound {
			// Preserve the established disposition wording for a wholly absent
			// evidence entry while still keeping the gate closed.
			switch item.Disposition {
			case LegacyFactBackfill:
				report.Facts[name] = "backfill readback unverified"
			case LegacyFactRetain:
				report.Facts[name] = "immutable retention unverified"
			default:
				report.Facts[name] = "coverage evidence missing"
			}
			ready = false
			continue
		}
		if !legacyJ3bFactEvidenceHasIdentity(expectedItem, factEvidence) {
			report.Facts[name] = "source/scope/digest evidence missing"
			ready = false
			continue
		}
		if factEvidence.SourceSchema != expectedItem.SourceSchema || factEvidence.SourceTable != expectedItem.SourceTable || factEvidence.Scope != expectedItem.Scope {
			report.Facts[name] = "source/scope evidence drift"
			ready = false
			continue
		}
		switch item.Disposition {
		case LegacyFactBackfill:
			if !factEvidence.BackfillReadbackVerified {
				report.Facts[name] = "backfill readback unverified"
				ready = false
			} else if legacyJ3bFactEvidenceDigestMismatch(factEvidence) {
				report.Facts[name] = "backfill digest mismatch"
				ready = false
			} else {
				report.Facts[name] = "backfill readback verified"
			}
		case LegacyFactRetain:
			if !factEvidence.RetentionVerified {
				report.Facts[name] = "immutable retention unverified"
				ready = false
			} else if legacyJ3bFactEvidenceDigestMismatch(factEvidence) {
				report.Facts[name] = "immutable retention digest mismatch"
				ready = false
			} else {
				report.Facts[name] = "immutable retention verified"
			}
		default:
			report.Facts[name] = "coverage disposition missing"
			complete, ready = false, false
		}
	}
	for name := range provided {
		if _, known := expected[name]; !known {
			report.Facts[name] = "unknown inventory entry"
			complete, ready = false, false
		}
	}
	for name := range evidence {
		if _, known := expected[name]; !known {
			if _, alreadyReported := report.Facts[name]; !alreadyReported {
				report.Facts[name] = "unknown evidence entry"
			}
			complete, ready = false, false
		}
	}
	if _, unnamed := report.Facts["__unnamed__"]; unnamed {
		complete, ready = false, false
	}
	report.InventoryComplete = complete
	report.Ready = complete && ready
	return report
}

func legacyJ3bFactEvidenceHasIdentity(item LegacyJ3bFact, evidence LegacyJ3bFactEvidence) bool {
	if strings.TrimSpace(evidence.SourceSchema) == "" || strings.TrimSpace(evidence.SourceTable) == "" {
		return false
	}
	if evidence.evidenceFromJSON && !evidence.scopeSet {
		return false
	}
	return validInventoryDigest(legacyJ3bFactEvidenceDigest(evidence))
}

func legacyJ3bFactEvidenceDigest(evidence LegacyJ3bFactEvidence) string {
	for _, digest := range []string{evidence.Digest, evidence.SourceDigest, evidence.RetentionDigest, evidence.TargetDigest} {
		if value := strings.TrimSpace(digest); value != "" {
			return value
		}
	}
	return ""
}

func legacyJ3bFactEvidenceDigestMismatch(evidence LegacyJ3bFactEvidence) bool {
	source := strings.TrimSpace(evidence.SourceDigest)
	target := strings.TrimSpace(evidence.TargetDigest)
	return source != "" && target != "" && normalizeInventoryDigest(source) != normalizeInventoryDigest(target)
}

func validInventoryDigest(value string) bool {
	value = normalizeInventoryDigest(value)
	if len(value) != sha256.Size*2 {
		return false
	}
	_, err := hex.DecodeString(value)
	return err == nil
}

func normalizeInventoryDigest(value string) string {
	value = strings.ToLower(strings.TrimSpace(value))
	if strings.HasPrefix(value, "sha256:") {
		value = strings.TrimPrefix(value, "sha256:")
	}
	return value
}

// LegacyJ3bFactNames returns the stable, sorted fact identifiers so command
// layers can render an auditable checklist without depending on map order.
func LegacyJ3bFactNames() []string {
	names := make([]string, 0, len(LegacyJ3bFactInventory))
	for _, item := range LegacyJ3bFactInventory {
		names = append(names, item.Name)
	}
	sort.Strings(names)
	return names
}

// FormatLegacyJ3bFactCoverageFailure makes a compact error safe for a command
// layer. The deterministic ordering keeps failed gates reproducible.
func FormatLegacyJ3bFactCoverageFailure(report LegacyJ3bFactCoverageReport) string {
	if report.Ready {
		return ""
	}
	names := make([]string, 0, len(report.Facts))
	for name := range report.Facts {
		names = append(names, name)
	}
	sort.Strings(names)
	parts := make([]string, 0, len(names))
	for _, name := range names {
		parts = append(parts, fmt.Sprintf("%s: %s", name, report.Facts[name]))
	}
	return strings.Join(parts, "; ")
}
