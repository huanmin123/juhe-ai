// LegacyFactDisposition states the only two acceptable dispositions for a
// Node-owned J3b dataset/stats fact. A fact must either have an explicit Go
// target mapping or an explicit immutable-retention decision. It must never
// disappear from the inventory merely because no Go table exists yet.
type LegacyFactDisposition string

const (
	LegacyFactBackfill LegacyFactDisposition = "backfill"
	LegacyFactRetain   LegacyFactDisposition = "retain"
)

// LegacyJ3bFact describes one Node dataset/stats relation (or the narrowly
// scoped J3b row set inside a shared stats relation) that must be accounted
// for before a J3b owner cutover. Scope is empty for a whole table.
//
// Retain means immutable historical evidence must be retained outside a live
// Node execution path. It is not an assertion that retention has happened,
// and it is not permission to leave the Node owner active.
type LegacyJ3bFact struct {
	Name         string
	SourceSchema string
	SourceTable  string
	Scope        string
	Disposition  LegacyFactDisposition
	TargetSchema string
	TargetTable  string
	RetentionWhy string
}

// LegacyJ3bFactEvidence contains the independent evidence required to close
// an individual inventory disposition. Backfill verification must come from a
// complete bounded readback; retention verification must prove immutable
// preservation of the exact source/scope. Neither field is inferred from a
// declared inventory entry.
type LegacyJ3bFactEvidence struct {
	SourceSchema string `json:"sourceSchema"`
	SourceTable  string `json:"sourceTable"`
	Scope        string `json:"scope"`
	// Digest is the exact digest captured for the source fact (or its
	// immutable retained copy). SourceDigest/TargetDigest are optional
	// readback details; when both are present they must match.
	Digest          string `json:"digest"`
	SourceDigest    string `json:"sourceDigest"`
	TargetDigest    string `json:"targetDigest"`
	RetentionDigest string `json:"retentionDigest"`

	BackfillReadbackVerified bool `json:"backfillReadbackVerified"`
	RetentionVerified        bool `json:"retentionVerified"`

	// These flags distinguish an explicit JSON scope field (including an
	// intentionally empty scope) from a zero-value Go struct literal. Direct
	// callers remain source-compatible while CLI evidence cannot omit scope.
	evidenceFromJSON bool
	scopeSet         bool
}

// UnmarshalJSON records field presence so a CLI evidence document cannot
// silently omit an empty-but-required scope value.
func (e *LegacyJ3bFactEvidence) UnmarshalJSON(data []byte) error {
	type alias LegacyJ3bFactEvidence
	var decoded alias
	if err := json.Unmarshal(data, &decoded); err != nil {
		return err
	}
	var fields map[string]json.RawMessage
	if err := json.Unmarshal(data, &fields); err != nil {
		return err
	}
	*e = LegacyJ3bFactEvidence(decoded)
	e.evidenceFromJSON = true
	_, e.scopeSet = fields["scope"]
	return nil
}

// LegacyJ3bFactEvidenceDocument is the explicit, read-only input consumed by
// the maintenance inventory command. It contains observations only; it is
// never generated by this package and never used to perform a migration.
type LegacyJ3bFactEvidenceDocument struct {
	Facts map[string]LegacyJ3bFactEvidence `json:"facts"`
}

// LoadLegacyJ3bFactEvidence reads one complete evidence document. The caller
// supplies this path from an independently produced readback/retention
// report; an absent or malformed document is an input error, not readiness.
func LoadLegacyJ3bFactEvidence(path string) (map[string]LegacyJ3bFactEvidence, error) {
	path = strings.TrimSpace(path)
	if path == "" {
		return nil, fmt.Errorf("J3b inventory evidence requires an explicit file path")
	}
	data, err := os.ReadFile(path)
	if err != nil {
		return nil, fmt.Errorf("read J3b inventory evidence file: %w", err)
	}
	decoder := json.NewDecoder(bytes.NewReader(data))
	var document LegacyJ3bFactEvidenceDocument
	if err := decoder.Decode(&document); err != nil {
		return nil, fmt.Errorf("decode J3b inventory evidence file: %w", err)
	}
	var extra any
	if err := decoder.Decode(&extra); err != io.EOF {
		if err == nil {
			return nil, fmt.Errorf("decode J3b inventory evidence file: trailing JSON data")
		}
		return nil, fmt.Errorf("decode J3b inventory evidence file: %w", err)
	}
	if document.Facts == nil {
		return nil, fmt.Errorf("decode J3b inventory evidence file: facts object is required")
	}
	return document.Facts, nil
}

// LegacyJ3bFactCoverageReport is planning and evidence coverage only. Ready
// is deliberately fail-closed: it does not mean a schema was written or a
// data migration ran; it means every known Node legacy fact has a valid,
// independently verified disposition supplied by the caller.
type LegacyJ3bFactCoverageReport struct {
	Ready             bool              `json:"ready"`
	InventoryComplete bool              `json:"inventoryComplete"`
	Facts             map[string]string `json:"facts"`
}

