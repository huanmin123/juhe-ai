type ModelQualityScheduleClaimInput struct {
	OwnerID ModelQualityClaimOwnerID
	// LeaseDuration is applied to one PostgreSQL clock_timestamp() inside
	// each claim write. Callers cannot extend a lease with a skewed host clock.
	LeaseDuration time.Duration
	Limit         int
}

// ModelQualityScheduleClaim is a durable scheduler hand-off. The adapter must
// atomically select only active, owned accounts and persist Lease before
// returning it. AccountConfigRevision is captured for the model-check payload
// and must not be confused with the schedule revision.
type ModelQualityScheduleClaim struct {
	Schedule              ModelQualitySchedule
	Policy                ModelQualityPolicyRecord
	AccountConfigRevision modelquality.AccountRevision
	Lease                 ModelQualityScheduleLease
}

type ModelQualityScheduleClaimer interface {
	ClaimDueModelQualitySchedules(context.Context, ModelQualityScheduleClaimInput) ([]ModelQualityScheduleClaim, error)
}

type ModelQualityScheduleCompletionStatus string

