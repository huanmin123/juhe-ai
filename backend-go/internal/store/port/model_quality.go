// ModelQualityPolicyRecord represents either a persisted policy or the
// implicit default policy used when no policy row exists. The distinction is
// needed by an adapter so an optimistic write at revision zero can atomically
// create the first durable row instead of overwriting an existing one.
type ModelQualityPolicyRecord struct {
	Policy    modelquality.Policy
	Persisted bool
	CreatedAt *time.Time
	UpdatedAt *time.Time
}

type ModelQualityPolicySaveInput struct {
	SystemAccountID string
	// ExpectedRevision is compared atomically with the durable policy revision.
	// Zero means the implicit default / first-row generation, not an omitted
	// fence.
	ExpectedRevision         modelquality.PolicyRevision
	Profile                  modelquality.Profile
	ManualEnforcementEnabled bool
	PenaltyThreshold         int
	PenaltyAction            modelquality.Action
	RecoveryInterval         time.Duration
	UpdatedAt                time.Time
}

type ModelQualityPolicySaveStatus string

const (
	ModelQualityPolicySaved    ModelQualityPolicySaveStatus = "saved"
	ModelQualityPolicyConflict ModelQualityPolicySaveStatus = "conflict"
)

type ModelQualityPolicySaveResult struct {
	Status ModelQualityPolicySaveStatus
	Policy ModelQualityPolicyRecord
}

// ModelQualityPolicyReader deliberately returns the effective policy: callers
// must never independently recreate a default and accidentally use different
// defaults from the durable adapter.
type ModelQualityPolicyReader interface {
	ReadModelQualityPolicy(context.Context, string) (ModelQualityPolicyRecord, error)
}

type ModelQualityPolicyWriter interface {
	SaveModelQualityPolicy(context.Context, ModelQualityPolicySaveInput) (ModelQualityPolicySaveResult, error)
}

// ModelQualityScheduleLease identifies an acquired schedule lease. ClaimToken
// is generated by the durable adapter and is distinct from OwnerID so a later
// claim by the same process cannot complete a stale prior lease.
type ModelQualityScheduleLease struct {
	OwnerID    ModelQualityClaimOwnerID
	ClaimToken ModelQualityScheduleClaimToken
	Until      time.Time
}

type ModelQualityClaimOwnerID string
type ModelQualityScheduleClaimToken string

type ModelQualitySchedule struct {
	ID              string
	SystemAccountID string
	AccountID       string
	Model           string
	Interval        time.Duration
	Enabled         bool
	Revision        modelquality.ScheduleRevision
	NextRunAt       time.Time
	LastRunID       string
	LastRunAt       *time.Time
	LastRunStatus   *modelquality.RunStatus
	Lease           *ModelQualityScheduleLease
	CreatedAt       time.Time
	UpdatedAt       time.Time
}

// ModelQualityScheduleUpsertInput changes the one schedule owned by the
// `(system_account_id, account_id)` relation. ExpectedRevision is optional only
// for the Node-compatible UI update path; a present zero explicitly requires
// that no durable schedule exists yet.
type ModelQualityScheduleUpsertInput struct {
	SystemAccountID  string
	AccountID        string
	Model            string
	Interval         time.Duration
	Enabled          bool
	ExpectedRevision *modelquality.ScheduleRevision
	UpdatedAt        time.Time
}

type ModelQualityScheduleDeleteInput struct {
	SystemAccountID string
	ScheduleID      string
	// ExpectedRevision is nil only for the legacy Node-compatible delete path.
	// New Go callers should provide it to avoid deleting a schedule edited after
	// it was displayed.
	ExpectedRevision *modelquality.ScheduleRevision
}

