// ModelQualityRecoveryLease is separate from ModelQualityScheduleLease to
// make it impossible to accidentally use a schedule claim to clear a quality
// isolation generation.
type ModelQualityRecoveryLease struct {
	OwnerID    ModelQualityClaimOwnerID
	ClaimToken ModelQualityRecoveryClaimToken
	Until      time.Time
}

type ModelQualityRecoveryClaimToken string

// ModelQualityEnforcementRecord is the durable control-plane state for one
// account. AccountConfigRevision starts as the pre-mutation account snapshot
// used to apply this enforcement generation, then a recovery claim refreshes
// it to that claim's current account revision. Recovery completion must compare
// it with its own expected revision and the current account row.
type ModelQualityEnforcementRecord struct {
	AccountID             string
	SystemAccountID       string
	Token                 modelquality.EnforcementToken
	State                 ModelQualityEnforcementState
	Action                modelquality.Action
	TriggerRunID          string
	PolicyRevision        modelquality.PolicyRevision
	AccountConfigRevision modelquality.AccountRevision
	BeforeStatus          modelquality.AccountStatus
	AfterStatus           modelquality.AccountStatus
	// FallbackWasEnabled and SuperPriorityWasEnabled are the account facts
	// captured before this enforcement generation. They remain durable audit
	// facts even when a later action changes one of the live account flags.
	FallbackWasEnabled      bool
	SuperPriorityWasEnabled bool
	RecoveryDueAt           *time.Time
	RecoveryLease           *ModelQualityRecoveryLease
	LastRecoveryRunID       string
	StartedAt               time.Time
	ClearedAt               *time.Time
	UpdatedAt               time.Time
}

type ModelQualityEnforcementApplyInput struct {
	SystemAccountID string
	AccountID       string
	RunID           string
	Trigger         modelquality.Trigger
	Action          modelquality.Action
	// ExpectedPolicyRevision and ExpectedAccountConfigRevision are both CAS
	// fences. The adapter reads policy/account and applies the chosen account
	// mutation plus enforcement record in one transaction.
	ExpectedPolicyRevision        modelquality.PolicyRevision
	ExpectedAccountConfigRevision modelquality.AccountRevision
	RecoveryInterval              time.Duration
	Message                       string
	DecidedAt                     time.Time
}

